"""Create (or reuse) the dedicated load-test user and seed a fixed dataset.

Only ever touches the load-test account (see common.py). Everything goes through
the public API, so the seed works against any running server.

    python -m loadtest.seed                 # create if missing, reuse if complete
    python -m loadtest.seed --reset         # delete the load-test user and seed again
    python -m loadtest.seed --host http://127.0.0.1:8002

The dataset is generated by `random.Random(SEED)`: the same rows every time, dated
relative to the day of seeding (analytics look at "this month", so data must be recent).
Re-seed with --reset before a before/after series so both runs see identical data.
"""
